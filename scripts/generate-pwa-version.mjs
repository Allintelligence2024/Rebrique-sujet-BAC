import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const files = ["index.html", "assets/styles.css", "sw.js"];
for (const directory of ["js", "data"]) {
  const walk = (base) =>
    readdirSync(base, { withFileTypes: true }).flatMap((entry) => {
      const path = join(base, entry.name);
      if (entry.isDirectory()) return walk(path);
      if (path.endsWith("app-version.js")) return [];
      return [path];
    });
  files.push(...walk(join(root, directory)).map((path) => relative(root, path)));
}
const hash = createHash("sha256");
for (const file of files.sort()) {
  hash.update(file);
  hash.update(readFileSync(join(root, file)));
}
const buildId = hash.digest("hex").slice(0, 12);
writeFileSync(
  join(root, "js", "app-version.js"),
  `// Generated by scripts/generate-pwa-version.mjs\nself.APP_BUILD_ID = "${buildId}";\n`
);
console.log(`PWA build id: ${buildId}`);
