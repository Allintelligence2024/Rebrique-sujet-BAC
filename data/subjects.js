/** Normalisation avancée du texte arabe */
export function normalizeArabic(text) {
  if (!text) return "";
  return text
    // Tatweel / Kashida (ـ)
    .replace(/\u0640/g, "")
    // Tashkeel / Harakat (diacritiques)
    .replace(/[\u064B-\u0652]/g, "")
    // Variantes de l'alef (إ / أ / آ / ٱ -> ا)
    .replace(/[إأآاٱ]/g, "ا")
    // Variantes de yaa / alef maqsura (ى / ي -> ي)
    .replace(/[ىي]/g, "ي")
    // Taa marbuta (ة -> ه)
    .replace(/ة/g, "ه")
    // Hamzas sur supports (ؤ -> و, ئ -> ي, ء -> vide)
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    .replace(/ء/g, "")
    // Ponctuations arabes et occidentales vers espaces
    .replace(/[،؟؛!?:.,;()\[\]{}"'\-–—\/\\_]/g, " ")
    .toLowerCase()
    .replace(/\s+/g, " ")
    .trim();
}

/** Nettoyage des clitiques arabes (préfixes الـ، كالـ، بالـ، فالـ، ولـ، إلخ) */
export function stripArabicClitics(word) {
  if (!word || word.length <= 3) return word;
  if (word.startsWith("كال") || word.startsWith("فال") || word.startsWith("بال")) return word.slice(3);
  if (word.startsWith("ولل")) return word.slice(3);
  if (word.startsWith("لل") && word.length > 3) return word.slice(2);
  if (word.startsWith("ال") && word.length > 3) return word.slice(2);
  if ((word.startsWith("و") || word.startsWith("ف") || word.startsWith("ب") || word.startsWith("ك") || word.startsWith("ل")) && word.length >= 4) {
    const rest = word.slice(1);
    if (rest.startsWith("ال") && rest.length > 3) return rest.slice(2);
    return rest;
  }
  return word;
}

